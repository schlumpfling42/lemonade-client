package net.rka.ai.agent.skills;

import com.fasterxml.jackson.core.JsonProcessingException;
import com.fasterxml.jackson.databind.ObjectMapper;
import net.rka.ai.agent.skills.SkillFile.NodeSpec;
import net.rka.ai.tools.ToolRegistry;

import java.util.ArrayList;
import java.util.LinkedHashSet;
import java.util.List;
import java.util.Map;
import java.util.Set;

/**
 * Shows what a skill does, so the user can judge it (anti-goal "hidden behavior"): its steps and where
 * each outcome leads, each step's prompt, and the tools it may use with those that need approval.
 * <ul>
 *   <li>{@link #outline}: the steps as plain text, one line per node, for the skill builder's review
 *       (a dialog can't render Mermaid).</li>
 *   <li>{@link #markdown}: a whole page with a Mermaid diagram, which {@link SkillLoader} writes as
 *       {@code <name>.md} next to each loaded user skill (generated, never read back).</li>
 *   <li>{@link #details}: the inputs, steps and tools sections both pages share.</li>
 * </ul>
 * Only the file is read, never the node kinds: a node's wiring is its {@code next} and {@code on}, so a
 * {@code stopped} that isn't mapped (which ends the skill with an error) doesn't show.
 */
public final class SkillDiagram {

    /**
     * The first line of every {@link #markdown} page: {@link SkillLoader} only overwrites a {@code <name>.md}
     * that starts with it, so a page the user wrote is never replaced.
     */
    public static final String GENERATED_MARKER = "<!-- Generated by the app from the skill file; it is rewritten on every load. -->";

    // The fields shown as text blocks (prompts can be long); the rest are shown as compact values
    private static final Set<String> TEXT_FIELDS = Set.of("prompt", "question", "result");
    private static final ObjectMapper JSON = new ObjectMapper();

    private SkillDiagram() {
    }

    /**
     * The steps as text, the first line where the skill starts:
     * <pre>
     *   start -> collect
     *   collect (model; tools: runCommand) -> draft
     *   check (askUser) accept -> done, revise -> draft, cancel -> cancelled
     *   done (finish)
     *   cancelled (finish, error)
     * </pre>
     */
    public static String outline(SkillFile skill) {
        StringBuilder out = new StringBuilder("start -> ").append(skill.start()).append('\n');
        for (NodeSpec node : skill.nodes()) {
            out.append(node.id()).append(" (").append(node.kind());
            if (Boolean.TRUE.equals(node.fields().get("error"))) out.append(", error");
            List<String> tools = listedTools(node);
            if (!tools.isEmpty()) out.append("; tools: ").append(String.join(", ", tools));
            out.append(')');
            if (node.next() != null) out.append(" -> ").append(node.next());
            List<String> routes = new ArrayList<>();
            node.on().forEach((outcome, target) -> routes.add(outcome + " -> " + target));
            if (!routes.isEmpty()) out.append(node.next() == null ? " " : ", ").append(String.join(", ", routes));
            out.append('\n');
        }
        return out.toString();
    }

    /**
     * The page {@link SkillLoader} writes as {@code <name>.md}: name, tool and description, a Mermaid
     * flowchart of the steps (outcomes as edge labels), then {@link #details}.
     *
     * @param tools the app's tools, which say which listed tools need approval
     */
    public static String markdown(SkillFile skill, ToolRegistry tools) {
        StringBuilder out = new StringBuilder(GENERATED_MARKER).append("\n\n# Skill `").append(skill.name()).append("`\n\n");
        out.append("_Generated from `").append(skill.name()).append(".json` when the skills were loaded;"
                + " changes to this file are not read back._\n\n");
        out.append("Tool `").append(skill.toolName()).append("`: ").append(skill.description()).append("\n\n");
        out.append("## Diagram\n\n```mermaid\nflowchart TD\n");
        // "n_" + id: Mermaid reserves some words ("end") as node ids
        out.append("    start((start)) --> n_").append(skill.start()).append('\n');
        for (NodeSpec node : skill.nodes()) {
            String label = quoted(node.id() + " · " + node.kind());
            boolean terminal = node.next() == null && node.on().isEmpty();
            out.append("    n_").append(node.id()).append(terminal ? "([" + label + "])" : "[" + label + "]").append('\n');
            if (node.next() != null) out.append("    n_").append(node.id()).append(" --> n_").append(node.next()).append('\n');
            node.on().forEach((outcome, target) -> out.append("    n_").append(node.id())
                    .append(" -->|").append(quoted(outcome)).append("| n_").append(target).append('\n'));
        }
        out.append("```\n\n");
        out.append(details(skill, toolsNeedingApproval(skill, tools)));
        return out.toString();
    }

    /**
     * The inputs, each step with its fields (prompts, questions and results as text blocks), and the tools
     * the skill may use, those in {@code needApproval} marked: they ask the user before they run, unless
     * trusted.
     */
    public static String details(SkillFile skill, List<String> needApproval) {
        StringBuilder out = new StringBuilder("### Inputs\n\n");
        if (skill.inputs().isEmpty()) out.append("None.\n");
        for (SkillFile.Input input : skill.inputs()) {
            out.append("- `").append(input.name()).append("`").append(input.required() ? " (required)" : " (optional)")
                    .append(": ").append(input.description()).append('\n');
        }
        out.append("\n### Steps in detail\n");
        for (NodeSpec node : skill.nodes()) {
            out.append("\n**").append(node.id()).append("** · ").append(node.kind()).append('\n');
            node.fields().forEach((field, value) -> {
                if (TEXT_FIELDS.contains(field) && value instanceof String text) {
                    // four backticks: a prompt may contain a ``` code fence itself
                    out.append("\n").append(field).append(":\n\n````text\n").append(text.strip()).append("\n````\n");
                } else {
                    out.append("- ").append(field).append(": `").append(compact(value)).append("`\n");
                }
            });
        }
        out.append("\n### Tools\n\n");
        List<String> tools = tools(skill);
        if (tools.isEmpty()) out.append("None.\n");
        for (String tool : tools) {
            out.append("- `").append(tool).append('`')
                    .append(needApproval.contains(tool) ? ": asks for your approval before it runs, unless trusted" : "")
                    .append('\n');
        }
        return out.toString();
    }

    /** Every tool the skill's nodes list, each once, in file order. */
    public static List<String> tools(SkillFile skill) {
        Set<String> tools = new LinkedHashSet<>();
        for (NodeSpec node : skill.nodes()) tools.addAll(listedTools(node));
        return List.copyOf(tools);
    }

    /**
     * The listed tools that need the user's approval unless trusted ({@code @RequiresApproval} commands,
     * {@code @WritesFiles} file changes), the same tools the skill's {@code toolApproval} pauses for.
     */
    public static List<String> toolsNeedingApproval(SkillFile skill, ToolRegistry tools) {
        return tools(skill).stream().filter(tool -> tools.requiresApproval(tool) || tools.writesFiles(tool)).toList();
    }

    private static List<String> listedTools(NodeSpec node) {
        List<String> tools = new ArrayList<>();
        if (node.fields().get("tools") instanceof List<?> list) {
            for (Object tool : list) if (tool instanceof String name) tools.add(name);
        }
        return tools;
    }

    /** A Mermaid label in quotes; quotes inside become Mermaid's entity. */
    private static String quoted(String text) {
        return "\"" + text.replace("\"", "#quot;") + "\"";
    }

    /** A field value on one line: text as it is, anything else as JSON. */
    private static String compact(Object value) {
        if (value instanceof String text) return text.replaceAll("\\s+", " ");
        if (!(value instanceof Map<?, ?> || value instanceof List<?>)) return String.valueOf(value); // numbers, true/false
        try {
            return JSON.writeValueAsString(value);
        } catch (JsonProcessingException e) {
            return String.valueOf(value); // plain values from JSON always serialize
        }
    }
}
